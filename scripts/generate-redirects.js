/**
 * Generates public/_redirects from the content manifest.
 * Run: node scripts/generate-redirects.js
 * Called automatically via npm run prebuild.
 *
 * Cloudflare applies the first matching rule, and a redirect is followed even
 * when a static asset already exists at the request path. A wildcard fallback
 * over /projects therefore shadows every prerendered zone and project page, so
 * the known URLs are emitted as explicit rules ahead of anything else.
 */
const fs = require('fs');
const path = require('path');

const LOCALES = ['ar', 'en'];

const MANIFEST_PATH = path.join(__dirname, '..', 'src', 'app', 'content-manifest.json');
const OUT_PATH = path.join(__dirname, '..', 'public', '_redirects');

const header = `# Cloudflare Pages redirects — GENERATED by scripts/generate-redirects.js
# Do not hand-edit: regenerate with \`node scripts/generate-redirects.js\` (npm prebuild).
# Static rules live in that script; zone and project rules come from
# src/app/content-manifest.json.
#
# Ordering matters. Cloudflare applies the first matching rule and follows it even
# when a static asset exists at the same path, so the prerendered zone/project
# rules below must precede every wildcard.`;

const staticRules = `# Root redirect to default Arabic locale (301 = permanent)
/ /ar/ 301

# Legacy non-locale routes redirect to Arabic locale (trailing slash matches Angular routing)
/projects/* /ar/projects/:splat 301
/projects /ar/projects/ 301
/about /ar/about/ 301
/contact /ar/contact/ 301
/gallery /ar/gallery/ 301
/blog/* /ar/blog/:splat 301
/blog /ar/blog/ 301
/privacy /ar/privacy/ 301
/sadat-guide /ar/sadat-guide/ 301
/sadat-city-maps /ar/sadat-city-maps/ 301
/construction /ar/construction/ 301

# Removed FAQ feature — consolidate into Sadat Guide (preserve link equity)
/faq /ar/sadat-guide/ 301
/ar/faq /ar/sadat-guide/ 301
/en/faq /en/sadat-guide/ 301
/ar/faq/ /ar/sadat-guide/ 301
/en/faq/ /en/sadat-guide/ 301

# Removed payment-plans feature — send to homepage
/payment-plans /ar/ 301
/ar/payment-plans /ar/ 301
/en/payment-plans /en/ 301
/ar/payment-plans/ /ar/ 301
/en/payment-plans/ /en/ 301

# Removed investors feature — send to homepage
/investors /ar/ 301
/ar/investors /ar/ 301
/en/investors /en/ 301
/ar/investors/ /ar/ 301
/en/investors/ /en/ 301

# Removed units feature — send to projects
/units /ar/projects/ 301
/ar/units /ar/projects/ 301
/en/units /en/projects/ 301
/ar/units/ /ar/projects/ 301
/en/units/ /en/projects/ 301`;

const adminRules = `# Admin SPA routes (client-rendered, not prerendered)
/admin /admin/ 301
/admin/* /index.csr 200`;

// Only the trailing-slash form is emitted: it is the canonical form used by the
// sitemap and every <link rel="canonical">. The slash-less form is left to
// Cloudflare's own 308 normalisation so each page keeps exactly one 200 URL.
function contentRules(manifest) {
  const lines = [];
  for (const locale of LOCALES) {
    for (const zone of manifest.zones) {
      const url = `/${locale}/projects/${zone}/`;
      lines.push(`${url} ${url}index.html 200`);
    }
  }
  for (const locale of LOCALES) {
    for (const project of manifest.projects) {
      const url = `/${locale}/projects/${project.zoneSlug}/${project.slug}/`;
      lines.push(`${url} ${url}index.html 200`);
    }
  }
  return lines;
}

function buildRedirects(manifest) {
  const rules = contentRules(manifest);
  return [
    header,
    '',
    staticRules,
    '',
    `# Prerendered zone and project pages (${rules.length} rules from the content manifest).`,
    '# Slugs absent from the manifest have no prerendered page and fall through to a',
    '# real 404 — content added in the admin panel is served once the next build runs.',
    ...rules,
    '',
    adminRules,
    '',
  ].join('\n');
}

module.exports = { buildRedirects, MANIFEST_PATH, OUT_PATH };

if (require.main === module) {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  const output = buildRedirects(manifest);
  fs.writeFileSync(OUT_PATH, output, 'utf8');
  const ruleCount = output
    .split('\n')
    .filter(l => l.endsWith(' 200') && l.includes('/projects/')).length;
  console.log(
    `[redirects] ${manifest.zones.length} zones, ${manifest.projects.length} projects -> ${ruleCount} rules in public/_redirects`,
  );
}
